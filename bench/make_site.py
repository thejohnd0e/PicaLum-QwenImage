"""Builds docs/index.html (GitHub Pages) from bench/suite.json, verdicts.json and results.

Usage: python bench/make_site.py      (needs the webp images already in docs/img/bench)
"""
import html
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BENCH = ROOT / "bench"
DOCS = ROOT / "docs"

suite = json.loads((BENCH / "suite.json").read_text(encoding="utf-8"))
verdicts = json.loads((BENCH / "verdicts.json").read_text(encoding="utf-8"))
qres = json.loads((BENCH / "results/qwen/results.json").read_text(encoding="utf-8"))
gres = json.loads((BENCH / "results/gpt/results.json").read_text(encoding="utf-8"))
credits = {c["file"]: c for c in json.loads((BENCH / "inputs/credits.json").read_text(encoding="utf-8"))}
tiers_dir = BENCH / "tiers/results"

CAT = {"Fotografía": "Photography", "Creatividad": "Creativity", "Edición": "Photo editing"}
WIN = {"qwen": "Qwen wins", "gpt": "gpt-image-2 wins", "tie": "Tie"}
esc = html.escape

tally = {}
for t in suite:
    c = CAT[t["cat"]]
    tally.setdefault(c, {"qwen": 0, "tie": 0, "gpt": 0})
    tally[c][verdicts[t["id"]]["winner"]] += 1
total = {k: sum(v[k] for v in tally.values()) for k in ("qwen", "tie", "gpt")}


def mins(xs):
    return f"{sum(xs) / len(xs) / 60:.1f} min" if xs else "n/a"


q_t2i = [qres[t["id"]]["seconds"] for t in suite if t["mode"] == "t2i"]
q_edit = [qres[t["id"]]["seconds"] for t in suite if t["mode"] == "edit"]
g_all = [gres[t["id"]]["seconds"] for t in suite if t["id"] in gres]

score_rows = "".join(
    f"<tr><th scope=row>{c}</th><td>{v['qwen']}</td><td>{v['tie']}</td><td>{v['gpt']}</td></tr>" for c, v in tally.items()
)

# VRAM tiers table (from bench/tiers/run.sh), if present
tier_rows = ""
TIER_LABEL = {
    "12gb-balanced": "12 GB card · balanced",
    "8gb-compact": "Soft 8 GB cap · compact",
    "8gb-balanced": "Soft 8 GB cap · balanced",
}
TEST_LABEL = {"t2i_draft": "Text→image 1024², 20 steps", "t2i_standard_16x9": "Text→image 1.6 MP, 30 steps", "edit_snow": "Photo edit 1280 px, 30 steps"}
if tiers_dir.exists():
    for tier, label in TIER_LABEL.items():
        p = tiers_dir / tier / "results.json"
        if not p.exists():
            continue
        r = json.loads(p.read_text(encoding="utf-8"))
        for tid, tl in TEST_LABEL.items():
            x = r.get(tid)
            if not x:
                continue
            if "error" in x:
                tier_rows += f"<tr><th scope=row>{label}</th><td>{tl}</td><td colspan=3>failed: {esc(x['error'][:80])}</td></tr>"
            else:
                tier_rows += (
                    f"<tr><th scope=row>{label}</th><td>{tl}</td><td>{x['seconds']:.0f} s</td>"
                    f"<td>{x['secondsPerStep']:.2f}</td><td>{x['peakVramMb'] / 1024:.1f} GB</td></tr>"
                )

cards = []
for t in suite:
    tid = t["id"]
    v = verdicts[tid]
    cells = []
    for f in t.get("images", []):
        c = credits[f]
        stem = Path(f).stem
        cells.append(
            f'<figure class="in"><figcaption><b>Input photo</b><span>{esc(c["author"])} · {esc(c["license"])}</span></figcaption>'
            f'<a href="img/bench/in_{stem}.webp"><img src="img/bench/in_{stem}.webp" loading="lazy" alt="Input photo for {esc(v["title"])} by {esc(c["author"])}"></a></figure>'
        )
    for side, res, lab in (("qwen", qres, "Qwen-Image-2.1 · local RTX 3060"), ("gpt", gres, "gpt-image-2 · cloud")):
        secs = res.get(tid, {}).get("seconds")
        meta = f"{secs / 60:.1f} min" if secs else ""
        cells.append(
            f'<figure class="{side}"><figcaption><b>{lab}</b><span>{meta}</span></figcaption>'
            f'<a href="img/bench/{tid}_{side}.webp"><img src="img/bench/{tid}_{side}.webp" loading="lazy" '
            f'alt="{esc(v["title"])}, generated by {lab.split(" ·")[0]}"></a></figure>'
        )
    cards.append(
        f'<article id="{tid}"><header><p class="k">{CAT[t["cat"]]} · {"edit" if t["mode"] == "edit" else "text-to-image " + t.get("ar", "")}</p>'
        f'<h3>{esc(v["title"])}</h3><span class="w w-{v["winner"]}">{WIN[v["winner"]]}</span></header>'
        f'<details><summary>Prompt</summary><p>{esc(t["prompt"])}</p></details>'
        f'<div class="row">{"".join(cells)}</div><p class="note">{esc(v["note"])}</p></article>'
    )

faq = [
    ("What AI image model runs on a 12 GB GPU?",
     "Qwen-Image-2.1 (7B, open weights, September 2026) runs fully in VRAM on a 12 GB card such as an RTX 3060 when you use the int8 weights and load the text encoder, the image model and the VAE one at a time. PicaLum QwenImage does that for you: about 35 seconds for a 1024×1024 image and about 7 minutes at native 2K."),
    ("Can Qwen-Image-2.1 run on an 8 GB GPU?",
     "Not verified yet. The compact profile swaps the text encoder for a 6.3 GB w4a8 version and cuts peak VRAM by about 2.5 GB at the same speed, so it should fit 10 GB cards. We could only emulate 8 GB with a soft cap, and peak usage still went above 8 GB, so treat 8 GB cards as untested."),
    ("Is Qwen-Image-2.1 as good as gpt-image-2?",
     f"For photo editing, yes in our tests: {tally['Photo editing']['tie']} ties and {tally['Photo editing']['qwen']} win out of 8 edits. For text-to-image, no: gpt-image-2 won {tally['Photography']['gpt'] + tally['Creativity']['gpt']} of 12, mostly on prompt adherence and world knowledge."),
    ("Is it free to use commercially?",
     "The app is MIT. The Qwen-Image-2.1 weights are under the Qwen Research License, which does not allow commercial use without a separate license from Alibaba."),
]
faq_html = "".join(f"<details><summary>{esc(q)}</summary><p>{esc(a)}</p></details>" for q, a in faq)
